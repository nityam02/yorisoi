import { chromium } from 'playwright'
const out = process.argv[2] ?? '.'
const base = process.env.BASE ?? 'http://localhost:8080'
const rid = process.argv[3] ?? 'R001'
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1366, height: 900 } })
await page.request.delete(`${base}/api/residents/${rid}/plan`)
await page.goto(`${base}/#/${rid}`)
await page.waitForSelector('.gauge', { timeout: 60000 })
await page.getByRole('button', { name: 'Start the conversation' }).click()
await page.getByRole('button', { name: 'Use sample conversation' }).click()
const t0 = Date.now()
await page.getByRole('button', { name: 'Draft plan' }).click()
await page.waitForSelector('.form', { timeout: 180000 })
console.log('draft took', ((Date.now() - t0) / 1000).toFixed(1), 's')
await page.screenshot({ path: `${out}/3-plan.png` })
await page.screenshot({ path: `${out}/3-plan-full.png`, fullPage: true })
await page.getByRole('button', { name: 'Copies and approval' }).click()
await page.getByRole('button', { name: 'Mark as reviewed with resident' }).click()
await page.getByRole('button', { name: 'Approve plan' }).click()
await page.waitForSelector('.hanko', { timeout: 30000 })
await page.waitForTimeout(800)
await page.screenshot({ path: `${out}/4-approved.png` })
await page.getByRole('tab', { name: /Easy-read/ }).click()
await page.getByRole('button', { name: 'Write the copies' }).first().click()
await page.waitForSelector('.doc.md.easy h1, .doc.md.easy p', { timeout: 120000 })
await page.screenshot({ path: `${out}/5-easyread.png` })
await page.getByRole('tab', { name: /Helper card/ }).click()
await page.screenshot({ path: `${out}/6-card.png` })
await browser.close()
